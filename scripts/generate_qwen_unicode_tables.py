#!/usr/bin/env python3
"""Generate Unicode membership tables from Qwen's pinned tokenizer regex engine.

Requires tokenizers==0.22.2 only when regenerating; native code has no new
runtime dependency or process-locale requirement. All Unicode scalar values
are queried, including supplementary planes, rather than guessed from blocks.
"""
from pathlib import Path
import argparse
import hashlib


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    import tokenizers
    from tokenizers import Regex, pre_tokenizers
    assert tokenizers.__version__ == "0.22.2", tokenizers.__version__
    scalars = "".join(chr(cp) for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF)
    lines = [
        "// Generated by scripts/generate_qwen_unicode_tables.py; do not edit.",
        "// tokenizers 0.22.2 regex engine, exhaustive Unicode scalar membership.",
        "// Generator SHA-256: " + hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
        "namespace qw3::detail::unicode {",
        "struct Range { uint32_t first, last; };",
        "template <size_t N>",
        "inline bool contains(uint32_t cp, const Range (&ranges)[N]) {",
        "    size_t lo = 0, hi = N;",
        "    while (lo < hi) {",
        "        const size_t mid = lo + (hi - lo) / 2;",
        "        if (ranges[mid].last < cp) lo = mid + 1; else hi = mid;",
        "    }",
        "    return lo < N && ranges[lo].first <= cp;",
        "}", "",
    ]
    for name, pattern in (("letters", r"[^\p{L}]+"), ("numbers", r"[^\p{N}]+"),
                          ("marks", r"[^\p{M}]+"), ("spaces", r"\S+")):
        splitter = pre_tokenizers.Split(Regex(pattern), behavior="removed")
        ranges = []
        count = 0
        for piece, _ in splitter.pre_tokenize_str(scalars):
            for character in piece:
                cp = ord(character)
                count += 1
                if ranges and cp == ranges[-1][1] + 1:
                    ranges[-1][1] = cp
                else:
                    ranges.append([cp, cp])
        lines.append(f"inline constexpr Range {name}[] = {{")
        lines.extend(f"    {{0x{first:X}, 0x{last:X}}}," for first, last in ranges)
        lines.extend(["};", ""])
        print(name, len(ranges), "ranges", count, "scalars", flush=True)
    lines.extend(["} // namespace qw3::detail::unicode", ""])
    content = "\n".join(lines)
    if args.check:
        assert args.output.read_text() == content, "generated table differs"
    else:
        with args.output.open("x") as stream:
            stream.write(content)


if __name__ == "__main__":
    main()
