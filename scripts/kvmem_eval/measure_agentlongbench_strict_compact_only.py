#!/usr/bin/env python3
"""Measure/replay strict summary-only AgentLongBench branches.

The corresponding strict Compact+RAG artifact is the source of truth for the
question-blind summary.  This runner removes every retrieved passage and raw
tail, preserves the task instruction/question and frozen answer sampling, and
therefore measures Compact-only without regenerating or changing the summary.
Use ``--max-tokens 1`` for first-token-only latency sampling.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import statistics
import sys
from pathlib import Path
from typing import Any


ALB_ROOT = Path("/home/chaidi/AgentLongBench-Long")
BASE_PATH = ALB_ROOT / "script" / "compactRag" / "run_no_tail_cap64k.py"


def load_module(path: Path, name: str) -> Any:
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load module: {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


base = load_module(BASE_PATH, "alb_strict_compact_base")


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, 1):
            line = line.strip()
            if not line:
                continue
            value = json.loads(line)
            if not isinstance(value, dict):
                raise RuntimeError(
                    f"expected JSON object at {path}:{line_number}"
                )
            rows.append(value)
    return rows


def load_summary(
    *, slice_name: str, source_root: Path, sid: str
) -> tuple[str, dict[str, Any]]:
    checkpoint = base.read_json(source_root / "checkpoints" / f"{sid}.json")
    if slice_name == "1m":
        precomputed = checkpoint.get("precomputed_summary")
        if isinstance(precomputed, dict) and str(precomputed.get("summary") or "").strip():
            return str(precomputed["summary"]).strip(), {
                "provider": "deepseek",
                "model": "deepseek-v4-pro",
                "source_artifact": str(source_root / "checkpoints" / f"{sid}.json"),
                "source_summary_sha256": precomputed.get("summary_sha256"),
                "source_compaction_total_sec": float(
                    (precomputed.get("summary_timing") or {}).get("total_sec") or 0.0
                ),
                "source_compaction_machine": "remote DeepSeek service",
            }
    rounds = checkpoint.get("rounds") or {}
    completed = [
        row
        for row in rounds.values()
        if str(row.get("summary") or "").strip()
    ]
    if not completed:
        raise RuntimeError(f"strict checkpoint has no completed summary: {sid}")
    final = max(completed, key=lambda row: int(row.get("cursor_after", -1)))
    reused_rounds = {
        int(value)
        for value in (checkpoint.get("source_rounds_reused") or [])
    }
    boundary_rows = [
        row
        for key, row in rounds.items()
        if int(key) not in reused_rounds
        and str(row.get("summary") or "").strip()
    ]
    answer_path = source_root / "answers" / f"{sid}.json"
    answer_record = base.read_json(answer_path) if answer_path.exists() else {}
    boundary_total_sec = answer_record.get("boundary_compaction_total_sec")
    if not isinstance(boundary_total_sec, (int, float)):
        boundary_total_sec = sum(
            float((row.get("summary_timing") or {}).get("total_sec") or 0.0)
            for row in boundary_rows
        )
    return str(final["summary"]).strip(), {
        "provider": "qwen",
        "model": "Qwen3.6-27B",
        "source_artifact": str(source_root / "checkpoints" / f"{sid}.json"),
        "source_summary_sha256": final.get("summary_sha256"),
        # Rounds reused from the historical compact state occurred before the
        # final query and are outside the pre-answer boundary.  Charge only
        # the boundary rounds generated by the matching strict utility run.
        "source_compaction_total_sec": float(boundary_total_sec),
        "source_compaction_machine": "matching strict utility/latency run",
        "historical_compaction_rounds_excluded": sorted(reused_rounds),
        "boundary_compaction_rounds_charged": len(boundary_rows),
    }


def final_prompt(slice_name: str, sample: dict[str, Any], summary: str) -> str:
    _, history_label = base.compact.knowledge_history_labels(sample)
    instruction = base.compact.build_system_prompt(
        base.compact.question_type(sample), history_label
    )
    heading = (
        "Question-blind DeepSeek compact summary of earlier history:"
        if slice_name == "1m"
        else "Full-history compact summary:"
    )
    return (
        f"{instruction}\n\n"
        f"{heading}\n{summary}\n\n"
        f"Question:\n{sample.get('question') or ''}\n\n"
        "Do not explain and do not repeat the compact summary.\n\n"
        "Answer:"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--slice", choices=("512k", "1m"), required=True)
    parser.add_argument("--dataset", type=Path, required=True)
    parser.add_argument("--source-compact-rag-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--api-base", required=True)
    parser.add_argument("--model", default="Qwen3.6-27B-FP8")
    parser.add_argument("--tokenizer-path", required=True)
    parser.add_argument("--question-id", action="append", default=[])
    parser.add_argument("--limit", type=int)
    parser.add_argument("--max-tokens", type=int, default=1)
    parser.add_argument("--temperature", type=float, default=0.6)
    parser.add_argument("--top-p", type=float, default=0.95)
    parser.add_argument("--top-k", type=int, default=20)
    parser.add_argument("--thinking-budget", type=int, default=8192)
    parser.add_argument("--seed", type=int, default=20260722)
    parser.add_argument("--attempts", type=int, default=2)
    parser.add_argument("--timeout-sec", type=int, default=14400)
    parser.add_argument("--max-call-sec", type=int, default=14400)
    args = parser.parse_args()
    if args.max_tokens <= 0:
        raise SystemExit("--max-tokens must be positive")

    samples = base.compact.load_samples(args.dataset)
    if args.question_id:
        wanted = set(args.question_id)
        samples = [s for s in samples if base.compact.sample_id(s) in wanted]
        found = {base.compact.sample_id(s) for s in samples}
        if found != wanted:
            raise SystemExit(f"missing question IDs: {sorted(wanted - found)}")
    if args.limit is not None:
        samples = samples[: args.limit]

    client = base.ControlledApiClient(
        args.api_base,
        args.model,
        "dummy",
        args.timeout_sec,
        args.max_call_sec,
        args.tokenizer_path,
        "Qwen2TokenizerFast-pinned",
        temperature=args.temperature,
        top_p=args.top_p,
        thinking_budget=args.thinking_budget,
        api_backend="qw3",
        seed=args.seed,
    )
    existing = {
        str(row.get("stable_sample_id")): row
        for row in read_jsonl(args.output)
        if row.get("status") == "completed"
    }
    prompt_cap = 65_536 if args.slice == "512k" else 102_400
    for index, sample in enumerate(samples, 1):
        sid = base.compact.sample_id(sample)
        if sid in existing:
            print(f"[skip] {index}/{len(samples)} sid={sid}", flush=True)
            continue
        summary, provenance = load_summary(
            slice_name=args.slice,
            source_root=args.source_compact_rag_root,
            sid=sid,
        )
        prompt = final_prompt(args.slice, sample, summary)
        prompt_tokens, tokenizer = client.tokenize(prompt)
        # ControlledApiClient's tokenizer count excludes the small Qwen role
        # wrapper.  Reserve the same 16 tokens as the strict utility runner.
        if prompt_tokens + 16 > prompt_cap:
            raise RuntimeError(
                f"summary-only prompt exceeds cap: {sid} "
                f"{prompt_tokens}+16>{prompt_cap}"
            )
        result = client.chat(prompt, args.max_tokens, True)
        timing = result.get("timing") or {}
        ttft = timing.get("server_ttft_sec") or timing.get("ttft_sec")
        if not isinstance(ttft, (int, float)):
            raise RuntimeError(f"missing first-token timing: {sid}")
        answer = str(result.get("content") or "")
        evaluation = (
            None
            if args.max_tokens == 1
            else base.compact.evaluate_response(sample, answer)
        )
        reprefill_ttft = float(ttft)
        steady_latency = reprefill_ttft
        row = {
            "schema_version": 1,
            "status": "completed",
            "slice": args.slice,
            "method": "strict_full_history_compact_only_no_tail",
            "stable_sample_id": sid,
            "dataset_index": sample.get("dataset_index"),
            "question_type": base.compact.question_type(sample),
            "active_context_cap": prompt_cap,
            "active_prompt_tokens_local": prompt_tokens + 16,
            "prompt_tokenizer": tokenizer,
            "summary_tokens_local": client.tokenize(summary)[0],
            "raw_tail_tokens": 0,
            "retrieved_tokens": 0,
            "temperature": args.temperature,
            "top_p": args.top_p,
            "top_k": args.top_k,
            "thinking_budget": args.thinking_budget,
            "seed": args.seed,
            "max_tokens": args.max_tokens,
            "answer": answer if args.max_tokens > 1 else None,
            "finish_reason": result.get("finish_reason"),
            "answer_timing": timing,
            "query_ttft_sec": float(ttft),
            # The summary prompt did not exist in the pre-query history state;
            # this TTFT is its required cold re-prefill through the first token.
            "final_context_reprefill_ttft_sec": reprefill_ttft,
            "steady_pre_answer_latency_sec": steady_latency,
            "main_pre_answer_latency_sec": (
                float(provenance["source_compaction_total_sec"]) + steady_latency
            ),
            "evaluation": evaluation,
            "summary_provenance": provenance,
        }
        base.append_jsonl(args.output, row)
        print(
            f"[done] {index}/{len(samples)} sid={sid} "
            f"prompt={prompt_tokens + 16} ttft={float(ttft):.3f}s",
            flush=True,
        )

    rows = [
        row
        for row in read_jsonl(args.output)
        if row.get("status") == "completed"
        and row.get("slice") == args.slice
    ]
    values = [float(row["steady_pre_answer_latency_sec"]) for row in rows]
    print(json.dumps({
        "slice": args.slice,
        "method": "strict_full_history_compact_only_no_tail",
        "n": len(values),
        "steady_mean_sec": statistics.fmean(values) if values else None,
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
